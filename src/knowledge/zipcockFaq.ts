export function findZipcockAnswer(query: string): string | null {
  const clean = query.trim().toLowerCase();
  if (!clean) return null;

  // 1. 직접 매칭 점수 계산
  let bestMatch: ZipcockKnowledgeItem | null = null;
  let highestScore = 0;

  for (const item of zipcockKnowledgeBase) {
    let score = 0;
    // 질문 자체 포함
    if (clean.includes(item.question.toLowerCase())) {
      score += 20;
    }
    // 키워드 매칭
    for (const kw of item.keywords) {
      if (clean.includes(kw.toLowerCase())) {
        score += 5;
      }
    }
    // 카테고리 매칭
    if (clean.includes(item.categoryLabel.toLowerCase())) {
      score += 3;
    }

    if (score > highestScore) {
      highestScore = score;
      bestMatch = item;
    }
  }

  if (bestMatch && highestScore >= 5) {
    return `${bestMatch.detailedAnswer}\n\n💡 **요약**: ${bestMatch.shortAnswer}`;
  }

  return null;
}
