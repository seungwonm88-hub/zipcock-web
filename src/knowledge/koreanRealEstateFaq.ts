export function findKoreanRealEstateKnowledge(query: string): string | null {
  const clean = query.trim().toLowerCase();
  if (!clean) return null;

  for (const domain of koreanRealEstateDomains) {
    if (
      clean.includes(domain.name.toLowerCase()) ||
      clean.includes(domain.id) ||
      domain.keyPoints.some(kp => clean.includes(kp.slice(0, 10).toLowerCase()))
    ) {
      return `[${domain.name} 안내]\n${domain.summary}\n\n**핵심 체크리스트**:\n${domain.keyPoints.map((p, i) => `${i + 1}. ${p}`).join('\n')}\n\n💡 집콕 AI 비서에게 해당 주제에 대한 상세 질문을 남겨주시면 정확한 법령 및 실무 가이드를 제공해 드립니다.`;
    }
  }

  // 핵심 키워드 기반 상세 답변
  if (clean.includes('126%') || clean.includes('공시가') || clean.includes('hug')) {
    return `**HUG 전세보증금 반환보증 가입 요건 (공시가격 126% 룰)**\n\n1. 산출 공식: **주택공시가격 × 140% (주택가격 산정비율) × 90% (보증한도 담보인정비율) = 126%**\n2. 예시: 공시가격 3억 원 아파트인 경우, 전세보증금이 **3억 7,800만 원(3억 × 1.26)** 이하여야 보증 가입이 승인됩니다.\n3. 선순위 채권(근저당)이 있는 경우: (선순위 채권 + 보증금) 합계가 공시가격의 126% 이내여야 합니다.\n\n*집콕재계약에서는 보증보험 가입 요건을 준수할 수 있도록 임대인 협조 특약을 기본 제공합니다.*`;
  }

  if (clean.includes('실거주') || clean.includes('거절') || clean.includes('가짜')) {
    return `**임대인 실거주 이유 갱신 거절 시 임차인 대응 & 손해배상 청구 요령**\n\n1. **확정일자 부여현황 열람**: 퇴거 후 관할 주민센터 또는 대법원 인터넷등기소에서 '임대차 정보제공요청서'를 제출하여 해당 주택에 신규 세입자의 전입/확정일자가 등록되었는지 확인합니다.\n2. **위반 확인 시 손해배상액 산정 (주택임대차보호법 제6조의3 제5항)**:\n   ① 갱신 거절 당시 월차임(환산월세) 3개월분\n   ② 임대인이 제3자에게 임대하여 얻은 환산월세 차액의 2년분\n   ③ 갱신 거절로 인하여 임차인이 입은 실제 손해액(이사비, 중개수수료 등) 중 **가장 큰 금액**을 청구할 수 있습니다.`;
  }

  if (clean.includes('임차권등기') || clean.includes('보증금 안') || clean.includes('못 돌려')) {
    return `**보증금 미반환 시 임차권등기명령 신청 & 대항력 유지 요령**\n\n1. **신청 시점**: 임대차 계약 만료일 다음 날부터 신청 가능 (계약 유지 중에는 불가)\n2. **신청 장소**: 임차주택 소재지 관할 지방법원 (전자소송 사이트에서 비대면 신청 가능)\n3. **핵심 주의점**: 반드시 **등기부등본에 임차권등기가 실제로 기재된 것을 확인한 후**에 이사를 가고 주민등록을 이전해야 대항력과 우선변제권이 100% 유지됩니다.\n4. 소요 비용(인지대, 송달료, 등록면허세 등)은 임대인에게 전액 청구할 수 있습니다.`;
  }

  if (clean.includes('중개보수') || clean.includes('요율') || clean.includes('수수료 체계')) {
    return `**공인중개사법에 따른 법정 중개보수 상한 요율 안내 (부가가치세 별도)**\n\n1. **주택 임대차 (전세/월세)**:\n   - 5천만 원 미만: 0.5% (한도액 20만 원)\n   - 5천만 ~ 1억 원: 0.4% (한도액 30만 원)\n   - 1억 ~ 9억 원: 0.3% (한도액 없음)\n   - 9억 ~ 12억 원: 0.4%\n   - 12억 ~ 15억 원: 0.5%\n   - 15억 원 이상: 0.6% 이내 협의\n\n2. **주택 매매**:\n   - 6억 ~ 9억 원: 0.4% | 9억 ~ 12억 원: 0.5% | 15억 이상: 0.7% 이내 협의\n\n*기존 계약 조건의 단순 연장이나 합의 갱신 시에는 당사자 간 비대면 공인 전자계약 체결을 통해 신속하고 편리하게 갱신을 완료할 수 있습니다.*`;
  }

  return null;
}
